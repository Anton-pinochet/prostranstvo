PROMPT_TEMPLATE = """Ты — обычный человек, который переписывается с другом в мессенджере. НЕ психолог, НЕ консультант. Сгенерируй {n} коротких диалогов «ситуация → реакция друга».

Тема: {topic}

ПРАВИЛА:
1. Ситуация: 1 предложение от первого лица, живой разговорный русский. 20–200 символов.
2. Реакция: 1–2 предложения, ЖИВАЯ РЕАКЦИЯ в чате. НЕ совет, НЕ «попробуй», «расслабься», «йога», «ванна», «прогулка». Только: удивление, сочувствие, вопрос, шутка, личный опыт.
3. НЕ императив («сделай», «попробуй»). НЕ начинай support с глагола.
4. НЕ слова «поддержка», «рекомендация», «совет», «психолог», «терапия».
5. В серьёзных — НЕ «всё будет хорошо», «не переживай». Вместо: «Понимаю», «Это тяжело», «Я рядом», «Расскажи».
6. В радостных — «Ого, круто!», «Да ладно?», «Молодец!».
7. Каждая пара — уникальная.

ПРИМЕРЫ:
- «Сегодня на работе всё валилось из рук» → «Ого, бывает. А что именно пошло не так?»
- «Поссорился с женой из-за ерунды» → «Блин, знакомо. Из-за чего хоть?»
- «Не могу уснуть, мысли крутятся» → «О, это моё. О чём думаешь?»
- «Чувствую себя одиноко вечером» → «Понимаю. Хочешь поговорить?»
- «Начальник наорал при всех» → «Ого, это жесть. Как ты?»
- «Расстался с девушкой» → «Это тяжело. Держись. Хочешь рассказать?»
- «Всё навалилось сразу» → «Ох, знакомо. Держись. Что случилось?»
- «Хочу просто поговорить» → «Конечно, я здесь. О чём?»

Формат ответа — строго JSON-массив, без markdown, без текста до и после:
[{{"situation": "...", "support": "..."}}]

Сгенерируй {n} пар по теме «{topic}»."""

def call_ollama(prompt, retries=2):
    url = f"{OLLAMA_HOST}/api/generate"
    payload = {
        "model": MODEL,
        "prompt": prompt,
        "stream": False,
        "options": {"temperature": 0.8, "num_predict": 1500},
    }
    for attempt in range(retries + 1):
        try:
            r = requests.post(url, json=payload, timeout=TIMEOUT)
            if r.status_code == 200:
                return r.json().get("response", "")
        except requests.exceptions.Timeout:
            print(f"  ! таймаут (попытка {attempt+1}/{retries+1})", flush=True)
        except Exception as e:
            print(f"  ! ошибка: {e}", flush=True)
        time.sleep(3)
    return ""

def parse_json(text):
    text = re.sub(r'^```(?:json)?\s*', '', text.strip())
    text = re.sub(r'\s*```$', '', text)
    match = re.search(r'\[.*\]', text, re.DOTALL)
    if match:
        try:
            data = json.loads(match.group(0))
            if isinstance(data, list):
                return data
        except json.JSONDecodeError:
            pass
    return []

def is_bad(s):
    if not s or len(s) < 15 or len(s) > 250:
        return True
    if re.search(r'[a-zA-Z]{3,}', s):
        return True
    bad = ["будь позитивнее", "не переживай", "всё будет хорошо",
           "просто не думай", "улыбнись", "всё пройдёт",
           "попробуй", "расслабься", "йога", "ванна", "прогулка",
           "рекомендую", "советую", "психолог", "терапия"]
    low = s.lower()
    if any(b in low for b in bad):
        return True
    return False

def log(msg):
    print(msg, flush=True)

def main():
    all_pairs = []
    seen = set()

    # Загружаем уже сгенерированные темы (продолжение)
    done_topics = set()
    try:
        with open(OUTPUT, encoding="utf-8") as f:
            for line in f:
                d = json.loads(line)
                done_topics.add(d.get("topic", ""))
                all_pairs.append(d)
                seen.add(d["support"].lower()[:50])
    except FileNotFoundError:
        pass
    log(f"Уже сгенерировано тем: {len(done_topics)}, пар: {len(all_pairs)}")


    total = len(TOPICS) * ROUNDS_PER_TOPIC
    log(f"Модель: {MODEL} @ {OLLAMA_HOST}")
    log(f"Тем: {len(TOPICS)}, раундов: {ROUNDS_PER_TOPIC}, всего запросов: {total}")

    pbar = tqdm(total=total, desc="Генерация", unit="запрос", ncols=100, file=sys.stdout)

    for topic_idx, topic in enumerate(TOPICS, 1):
        if topic in done_topics:
            log(f"\n=== [{topic_idx}/{len(TOPICS)}] {topic} — пропуск (уже готово) ===")
            pbar.update(ROUNDS_PER_TOPIC)
            continue
        log(f"\n=== [{topic_idx}/{len(TOPICS)}] {topic} ===")

        for round_idx in range(1, ROUNDS_PER_TOPIC + 1):
            prompt = PROMPT_TEMPLATE.format(n=PAIRS_PER_REQUEST, topic=topic)
            response = call_ollama(prompt)
            pairs = parse_json(response)

            added = 0
            for p in pairs:
                sit = p.get("situation", "").strip()
                sup = p.get("support", "").strip()
                if is_bad(sit) or is_bad(sup):
                    continue
                key = sup.lower()[:50]
                if key in seen:
                    continue
                seen.add(key)
                all_pairs.append({"situation": sit, "support": sup, "topic": topic})
                added += 1

            pbar.update(1)
            pbar.set_postfix({"тема": f"{topic_idx}/{len(TOPICS)}", "пар": len(all_pairs)})
            log(f"  раунд {round_idx}/{ROUNDS_PER_TOPIC}: +{added} (всего {len(all_pairs)})")

            if round_idx == ROUNDS_PER_TOPIC:
                with open(OUTPUT, "w", encoding="utf-8") as f:
                    for row in all_pairs:
                        f.write(json.dumps(row, ensure_ascii=False) + "\n")
                log(f"  (сохранено: {len(all_pairs)} пар)")

    pbar.close()

    with open(OUTPUT, "w", encoding="utf-8") as f:
        for row in all_pairs:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")

    log(f"\n=== ГОТОВО: {len(all_pairs)} пар → {OUTPUT} ===")

if __name__ == "__main__":
    main()
